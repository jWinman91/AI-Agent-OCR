import traceback
from pathlib import Path
from typing import Any

import matplotlib
import pandas as pd
from src.server.analysis_policy import analysis_globals, compile_analysis
from src.utils.data_models import AnalyserResponse, AnalyserResult


def execute_python_code(
    analyser_response: AnalyserResponse,
    data_file_path: Path | None,
    downloaded_data_file_path: Path | None,
    *,
    output_dir: Path = Path("plots"),
) -> AnalyserResult:
    """
    Executes AST-filtered analysis code. This is not a hostile-code sandbox.

    :param AnalyserResponse: AnalyserResponse object containing the Python code to
    execute and its summary.
    :param data_file_path: Path to the data file generated by the data extractor
    agent.
    :param downloaded_data_file_path: Path to the data file generated by the data
    downloader agent.
    :param output_dir: Directory permitted for CSV and PNG output writes.
    :return: AnalyserResult object containing the paths to the generated plot and
    dataframe or an error message if execution fails.
    """
    df = pd.read_csv(data_file_path) if data_file_path else None
    df_download = (
        pd.read_csv(downloaded_data_file_path) if downloaded_data_file_path else None
    )
    if (df is None or df.empty) and (df_download is None or df_download.empty):
        return AnalyserResult(
            df_file_path=None,
            data_file_path=None,
            plot_path=None,
            code_summary=analyser_response.code_summary,
            python_code=analyser_response.python_code,
            error_message=(
                "No data available for analysis: both datasets are missing or empty."
            ),
        )
    context: dict[str, Any] = {
        "df": df,
        "df_download": df_download,
        "plot_path": "",
        "df_file_path": "",
    }

    try:
        code = compile_analysis(analyser_response.python_code)
        context.update(analysis_globals(output_dir))
        # Styles and rcParams set by the analysis would otherwise stay active for
        # every later analysis in this backend process.
        with matplotlib.rc_context():
            exec(code, context)
        return AnalyserResult(
            df_file_path=_output_path(context["df_file_path"]),
            data_file_path=data_file_path or downloaded_data_file_path,
            plot_path=_output_path(context["plot_path"]),
            code_summary=analyser_response.code_summary,
            python_code=analyser_response.python_code,
            error_message=None,
        )
    except Exception:
        return AnalyserResult(
            df_file_path=None,
            data_file_path=None,
            plot_path=None,
            code_summary=analyser_response.code_summary,
            python_code=analyser_response.python_code,
            error_message=traceback.format_exc(),
        )


def _output_path(value: object) -> Path | None:
    """Turns an output path the analysis code assigned into a Path, or None if it
    left the variable unset (empty string) - pydantic would otherwise turn ""
    into Path("."), which clients then try to download."""
    return Path(str(value)) if value else None
